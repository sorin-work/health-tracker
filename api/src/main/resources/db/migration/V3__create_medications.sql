create table medications (
    id           bigint generated by default as identity primary key,
    user_id      bigint       not null references users (id) on delete cascade,
    name         varchar(120) not null,
    dosage       varchar(60),
    instructions varchar(500),
    as_needed    boolean      not null default false,
    start_date   date         not null,
    end_date     date,
    active       boolean      not null default true,
    created_at   timestamptz  not null default now()
);

create index medications_user_idx on medications (user_id);

-- Times of day a scheduled medication is taken, in the user's local time.
create table medication_times (
    medication_id bigint not null references medications (id) on delete cascade,
    time_of_day   time   not null,
    primary key (medication_id, time_of_day)
);

create table dose_logs (
    id            bigint generated by default as identity primary key,
    medication_id bigint       not null references medications (id) on delete cascade,
    user_id       bigint       not null references users (id) on delete cascade,
    scheduled_at  timestamptz  not null,
    status        varchar(16)  not null,
    recorded_at   timestamptz  not null,
    note          varchar(500),
    constraint dose_logs_medication_time_key unique (medication_id, scheduled_at)
);
